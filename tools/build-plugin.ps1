<#
.SYNOPSIS
    Builds the UtilityBelt plugin for AC:Unreal.

.DESCRIPTION
    1. Lints plugin/src/*.lua for APIs the client sandbox does not provide.
    2. Concatenates the modules (in file-name order) into dist/utilitybelt/main.lua.
    3. Stamps the version into main.lua and plugin.json.
    4. Copies default.json and assets.
    5. Unless -NoPackage: zips dist/utilitybelt, writes a SHA-256 checksum and latest.json.

    Runs on Windows PowerShell 5.1 and PowerShell 7 (GitHub's Linux runners).

.EXAMPLE
    ./tools/build-plugin.ps1                      # dev build, version 0.0.0-dev, no zip
    ./tools/build-plugin.ps1 -Version 0.1.0       # release build with zip, checksum, latest.json
#>
param(
    [string]$Version = "0.0.0-dev",
    [string]$Repo = "Schneebs/AC_Unreal_UtilityBelt_ILT",
    [switch]$NoPackage
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$pluginDir = Join-Path $root "plugin"
$srcDir = Join-Path $pluginDir "src"
$dist = Join-Path $root "dist"
$out = Join-Path $dist "utilitybelt"
$utf8 = New-Object System.Text.UTF8Encoding $false   # no BOM

if ($Version -notmatch '^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$') {
    throw "Version '$Version' is not semantic (e.g. 0.1.0 or 0.2.0-beta.1)."
}
if ($Version -eq "0.0.0-dev" -and -not $PSBoundParameters.ContainsKey("NoPackage")) { $NoPackage = $true }

# --- 1. Lint ---------------------------------------------------------------
# Patterns for functions the AC:Unreal Lua sandbox removes (see Docs/Plugins/PublicAPI.md).
$forbidden = [ordered]@{
    'require\s*\('                          = 'require (no modules in the sandbox)'
    '(^|[^\w.])(io|os|debug|coroutine)\.'   = 'io/os/debug/coroutine libraries'
    '(^|[^\w.])(x?pcall)\s*\('              = 'pcall/xpcall'
    '(^|[^\w.])(set|get)metatable\s*\('     = 'metatables'
    '(^|[^\w.])(load|loadstring|dofile|loadfile)\s*\(' = 'dynamic loading'
    '(^|[^\w.])print\s*\('                  = 'print (use the log or notice service)'
    '(^|[^\w.])collectgarbage\s*\('         = 'collectgarbage'
    'string\.(find|match|gmatch|gsub|dump)\b' = 'string pattern functions (use string.findplain / regexmatch)'
    ':(find|match|gmatch|gsub)\s*\('        = 'string pattern methods (use string.findplain / regexmatch)'
}
$files = Get-ChildItem -Path $srcDir -Filter *.lua | Sort-Object Name
if (-not $files) { throw "No Lua modules found in $srcDir" }
$problems = @()
foreach ($f in $files) {
    $n = 0
    foreach ($line in [System.IO.File]::ReadAllLines($f.FullName)) {
        $n++
        $code = $line
        $c = $code.IndexOf('--')
        if ($c -ge 0) { $code = $code.Substring(0, $c) }   # drop line comments
        foreach ($p in $forbidden.Keys) {
            if ($code -match $p) { $problems += ("{0}:{1}: {2}" -f $f.Name, $n, $forbidden[$p]) }
        }
    }
}
if ($problems.Count -gt 0) {
    $problems | ForEach-Object { Write-Host "lint: $_" -ForegroundColor Red }
    throw "Lint failed: $($problems.Count) sandbox violation(s)."
}

# --- 2/3. Concatenate and stamp ---------------------------------------------
if (Test-Path $out) { Get-ChildItem -Path $out -Force | Remove-Item -Recurse -Force }
else { New-Item -ItemType Directory -Force -Path $out | Out-Null }

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("-- UtilityBelt $Version for AC:Unreal. Generated by tools/build-plugin.ps1; edit plugin/src instead.")
foreach ($f in $files) {
    [void]$sb.AppendLine("")
    [void]$sb.AppendLine("-- ==== $($f.Name) ====")
    [void]$sb.Append(([System.IO.File]::ReadAllText($f.FullName)).TrimEnd()).AppendLine()
}
$main = $sb.ToString().Replace("@VERSION@", $Version).Replace("`r`n", "`n")
[System.IO.File]::WriteAllText((Join-Path $out "main.lua"), $main, $utf8)

$manifest = [System.IO.File]::ReadAllText((Join-Path $pluginDir "plugin.json"))
$stamped = [regex]::Replace($manifest, '"version"\s*:\s*"[^"]*"', ('"version": "{0}"' -f $Version), 1)
if ($stamped -eq $manifest -and $manifest -notmatch ('"version"\s*:\s*"{0}"' -f [regex]::Escape($Version))) {
    throw "plugin.json has no version field to stamp."
}
[System.IO.File]::WriteAllText((Join-Path $out "plugin.json"), $stamped.Replace("`r`n", "`n"), $utf8)

# --- 4. Profile defaults and assets ------------------------------------------
Copy-Item -Path (Join-Path $pluginDir "default.json") -Destination $out
foreach ($sub in @("images", "sounds")) {
    $from = Join-Path (Join-Path $pluginDir "assets") $sub
    if ((Test-Path $from) -and (Get-ChildItem -Path $from -File -Recurse | Where-Object { $_.Name -ne ".gitkeep" })) {
        Copy-Item -Path $from -Destination (Join-Path $out $sub) -Recurse
        Get-ChildItem -Path (Join-Path $out $sub) -Filter ".gitkeep" -Recurse -Force | Remove-Item -Force
    }
}
Write-Host "Built $out ($Version, $($files.Count) modules)"

if ($NoPackage) { return }

# --- 5. Package ----------------------------------------------------------------
$zipName = "utilitybelt-$Version.zip"
$zip = Join-Path $dist $zipName
if (Test-Path $zip) { Remove-Item $zip -Force }
# Build the zip by hand: Windows PowerShell 5.1's Compress-Archive writes backslash
# entry names, which the zip spec forbids. Archive root is the utilitybelt folder.
Add-Type -AssemblyName System.IO.Compression, System.IO.Compression.FileSystem
$archive = [System.IO.Compression.ZipFile]::Open($zip, [System.IO.Compression.ZipArchiveMode]::Create)
try {
    foreach ($file in Get-ChildItem -Path $out -File -Recurse | Sort-Object FullName) {
        $relative = $file.FullName.Substring($out.Length).TrimStart('\', '/').Replace('\', '/')
        [void][System.IO.Compression.ZipFileExtensions]::CreateEntryFromFile(
            $archive, $file.FullName, "utilitybelt/$relative", [System.IO.Compression.CompressionLevel]::Optimal)
    }
} finally { $archive.Dispose() }
$hash = (Get-FileHash -Path $zip -Algorithm SHA256).Hash.ToLowerInvariant()
$size = (Get-Item $zip).Length
[System.IO.File]::WriteAllText("$zip.sha256", "$hash  $zipName`n", $utf8)

$tag = "v$Version"
$latest = [ordered]@{
    version = $Version
    tag     = $tag
    channel = $(if ($Version.Contains("-")) { "beta" } else { "stable" })
    repo    = $Repo
    plugin  = [ordered]@{
        id     = "utilitybelt"
        file   = $zipName
        url    = "https://github.com/$Repo/releases/download/$tag/$zipName"
        sha256 = $hash
        size   = $size
    }
    manager = $null
}
[System.IO.File]::WriteAllText((Join-Path $dist "latest.json"), ($latest | ConvertTo-Json -Depth 5), $utf8)
Write-Host "Packaged $zipName ($size bytes, sha256 $hash) and latest.json"
